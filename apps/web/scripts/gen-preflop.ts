/**
 * Build-time preflop tables (PLAN §0.1, §7.5): `npm run gen` (root, or `-w @rb/web`), from apps/web
 * `node scripts/gen-preflop.ts`. Writes `src/data/generated/preflop-equity.ts`, `finals.ts` and
 * their entries in `checksums.json`; commit all three. ⚠️ Never edit them by hand.
 *
 * - `preflop-equity`: the equity of each of the 169 starting-hand classes against 1..8 opponents
 *   holding random hands, as `win` and `split` in basis points (Uint16). Monte Carlo with the same
 *   `equity()` the HUD uses, 500,000 trials per cell (±0.14% at 95%), every cell seeded from the
 *   fixed table seed, dealt across `worker_threads`.
 * - `finals`: for each class, the exact number of boards (of all C(50,5) = 2,118,760) on which the
 *   hand finishes with each of the 10 display categories, from `finalCounts` (§6.6).
 *
 * Suits are symmetric, so one hand stands for a whole class (`classCards`). The layout of both
 * tables is read back by `src/data/preflopLayout.ts`.
 *
 * Options: `--threads N` (default: one per core), and for trial runs `--trials N` with `--out DIR`
 * (a different `--trials` never writes into the committed folder).
 */
import { resolve } from 'node:path';
import { parseArgs } from 'node:util';
import { deriveSeed, ZERO_SEED, type Seed128 } from '../src/core/rng.ts';
import {
  FINAL_CATEGORIES,
  FINALS_BOARDS,
  PREFLOP_CLASSES,
  PREFLOP_MAX_OPPONENTS,
} from '../src/data/preflopLayout.ts';
import { binaryModule, GENERATED_DIR, writeGenerated } from './generated.ts';
import {
  defaultThreads,
  runJobs,
  type FinalsResult,
  type Job,
  type JobResult,
  type McResult,
} from './table-jobs.ts';

/** Bumped whenever the method or the layout changes: `check-tables` then demands a regeneration. */
export const GENERATOR = 'gen-preflop@1';

/** Monte Carlo trials per cell of the committed table (PLAN §7.5). */
export const EQUITY_TRIALS = 500_000;

export const EQUITY_FILE = 'preflop-equity.ts';
export const FINALS_FILE = 'finals.ts';

/** The fixed seed of the table; every cell derives its own from it. */
export const TABLE_SEED: Seed128 = deriveSeed(ZERO_SEED, 'gen-preflop');

/** The seed of one cell under `parent` (the table seed, or `check-tables`' own). */
export function cellSeed(parent: Seed128, cls: number, nOpp: number): Seed128 {
  return deriveSeed(parent, 'cell', cls, nOpp);
}

/** A probability in [0, 1] as basis points (1 = 0.01 %). */
export function basisPoints(p: number): number {
  return Math.round(p * 10_000);
}

/** Position of the cell (class, nOpp) among the cells, class by class. */
export function cellIndex(cls: number, nOpp: number): number {
  return cls * PREFLOP_MAX_OPPONENTS + (nOpp - 1);
}

const CELLS = PREFLOP_CLASSES * PREFLOP_MAX_OPPONENTS;

/**
 * The equity table as bytes. Cell `i = cellIndex(class, nOpp)` owns the words `2 * i` (`win`) and
 * `2 * i + 1` (`split`), each a Uint16 in basis points. The bytes are stored in two planes, all
 * high bytes first and then all low bytes: the high bytes barely change from cell to cell, so gzip
 * shrinks this layout by about a fifth compared with whole words. `cells` is in cell order.
 */
export function encodeEquity(cells: readonly McResult[]): Uint8Array {
  if (cells.length !== CELLS) throw new RangeError(`need ${CELLS} cells, got ${cells.length}`);
  const words = CELLS * 2;
  const out = new Uint8Array(words * 2);
  cells.forEach((cell, i) => {
    const win = basisPoints(cell.win);
    const split = basisPoints(cell.split);
    if (win + split > 10_000) throw new RangeError(`cell ${i}: win + split is above 100%`);
    out[2 * i] = win >> 8;
    out[words + 2 * i] = win & 255;
    out[2 * i + 1] = split >> 8;
    out[words + 2 * i + 1] = split & 255;
  });
  return out;
}

/**
 * The finals table as bytes: word `class * 10 + k` is the number of boards on which the class
 * finishes with exactly category `k`, a Uint32, little-endian. `rows` is in class order.
 */
export function encodeFinals(rows: readonly (readonly number[])[]): Uint8Array {
  if (rows.length !== PREFLOP_CLASSES) {
    throw new RangeError(`need ${PREFLOP_CLASSES} rows, got ${rows.length}`);
  }
  const out = new Uint8Array(PREFLOP_CLASSES * FINAL_CATEGORIES * 4);
  const view = new DataView(out.buffer);
  rows.forEach((row, cls) => {
    if (row.length !== FINAL_CATEGORIES) {
      throw new RangeError(`class ${cls}: need ${FINAL_CATEGORIES} counts, got ${row.length}`);
    }
    const total = row.reduce((sum, n) => sum + n, 0);
    if (total !== FINALS_BOARDS) throw new RangeError(`class ${cls}: ${total} boards, not C(50,5)`);
    row.forEach((n, k) => view.setUint32(4 * (cls * FINAL_CATEGORIES + k), n, true));
  });
  return out;
}

function equityModule(bytes: Uint8Array, trials: number): string {
  return binaryModule(
    [
      `Generated by scripts/gen-preflop.ts (${GENERATOR}). Never edit by hand: \`npm run gen\``,
      'rewrites this file and `npm run gen:check` fails when it changes (PLAN section 7.5).',
      '',
      'Preflop equity of each of the 169 starting-hand classes against 1..8 opponents that hold',
      `random cards. Monte Carlo, ${trials} trials per cell, table seed ${TABLE_SEED}.`,
      '',
      `Layout: ${bytes.length} bytes = ${bytes.length / 2} Uint16 words in two planes: the high bytes of all`,
      'words, then the low bytes. The cell (class, nOpp) owns word 2 * (class * 8 + nOpp - 1), its',
      'win, and the next word, its split (the share of ties), each in basis points (1 = 0.01 %).',
      'equity = win + split. Class index: core/cards.ts classOf (AA = 0, AKs = 1, AKo = 13,',
      '22 = 168).',
    ],
    { PREFLOP_EQUITY_TRIALS: trials },
    'PREFLOP_EQUITY_B64',
    bytes,
  );
}

function finalsModule(bytes: Uint8Array): string {
  return binaryModule(
    [
      `Generated by scripts/gen-preflop.ts (${GENERATOR}). Never edit by hand: \`npm run gen\``,
      'rewrites this file and `npm run gen:check` fails when it changes (PLAN section 7.5).',
      '',
      'The final hand category by the river for each of the 169 starting-hand classes: exact, over',
      `all C(50,5) = ${FINALS_BOARDS} five-card boards of the other cards (one hand per class:`,
      'suits are symmetric).',
      '',
      'Layout: word class * 10 + k is the number of boards on which the hand finishes with exactly',
      'category k (0 high card, 1 pair, 2 two pair, 3 three of a kind, 4 straight, 5 flush,',
      '6 full house, 7 four of a kind, 8 straight flush, 9 royal flush), a Uint32, little-endian.',
      `The ten counts of a class add up to ${FINALS_BOARDS}.`,
    ],
    {},
    'FINALS_B64',
    bytes,
  );
}

export interface GenerateOptions {
  /** Monte Carlo trials per equity cell. */
  readonly trials: number;
  readonly threads: number;
  /** Where the modules and `checksums.json` are written. */
  readonly out: string;
  readonly log?: (line: string) => void;
}

/** The jobs in the order they are handed out: the slowest cells (most opponents) first. */
export function tableJobs(trials: number): Job[] {
  const jobs: Job[] = [];
  for (let nOpp = PREFLOP_MAX_OPPONENTS; nOpp >= 1; nOpp--) {
    for (let cls = 0; cls < PREFLOP_CLASSES; cls++) {
      jobs.push({ kind: 'mc', cls, nOpp, trials, seed: cellSeed(TABLE_SEED, cls, nOpp) });
    }
  }
  for (let cls = 0; cls < PREFLOP_CLASSES; cls++) jobs.push({ kind: 'finals', cls });
  return jobs;
}

/** Sorts the results of `tableJobs` into the two tables' order. */
export function collect(
  jobs: readonly Job[],
  results: readonly JobResult[],
): { cells: McResult[]; rows: (readonly number[])[] } {
  const cells = new Array<McResult>(CELLS);
  const rows = new Array<readonly number[]>(PREFLOP_CLASSES);
  jobs.forEach((job, i) => {
    const result = results[i] as JobResult;
    if (job.kind === 'mc') cells[cellIndex(job.cls, job.nOpp)] = result as McResult;
    else rows[job.cls] = (result as FinalsResult).counts;
  });
  return { cells, rows };
}

/** Builds both tables and writes them with their checksums. Returns the seconds it took. */
export async function generate(options: GenerateOptions): Promise<number> {
  const log = options.log ?? (() => undefined);
  const started = performance.now();
  const jobs = tableJobs(options.trials);
  const threads = `${options.threads} thread${options.threads === 1 ? '' : 's'}`;
  log(
    `${jobs.length} jobs on ${threads}: ${CELLS} cells x ${options.trials} trials, ` +
      `${PREFLOP_CLASSES} exact rows`,
  );
  let lastPercent = -1;
  const results = await runJobs(jobs, options.threads, (done) => {
    const percent = Math.floor((100 * done) / jobs.length / 10) * 10;
    if (percent > lastPercent) {
      lastPercent = percent;
      log(`  ${percent}%  ${((performance.now() - started) / 1000).toFixed(0)} s`);
    }
  });
  const { cells, rows } = collect(jobs, results);
  writeGenerated(options.out, EQUITY_FILE, equityModule(encodeEquity(cells), options.trials), {
    generator: GENERATOR,
    seed: TABLE_SEED,
    trials: options.trials,
  });
  writeGenerated(options.out, FINALS_FILE, finalsModule(encodeFinals(rows)), {
    generator: GENERATOR,
    seed: null,
    trials: null,
  });
  log(`wrote ${EQUITY_FILE}, ${FINALS_FILE} and checksums.json to ${options.out}`);
  return (performance.now() - started) / 1000;
}

function positiveInteger(text: string, name: string): number {
  const value = Number(text);
  if (!Number.isSafeInteger(value) || value < 1) {
    throw new Error(`--${name} needs a positive integer`);
  }
  return value;
}

if (import.meta.main) {
  try {
    const { values } = parseArgs({
      options: {
        trials: { type: 'string' },
        threads: { type: 'string' },
        out: { type: 'string' },
      },
      strict: true,
    });
    const trials =
      values.trials === undefined ? EQUITY_TRIALS : positiveInteger(values.trials, 'trials');
    const threads =
      values.threads === undefined ? defaultThreads() : positiveInteger(values.threads, 'threads');
    if (trials !== EQUITY_TRIALS && values.out === undefined) {
      throw new Error(
        `--trials other than ${EQUITY_TRIALS} needs --out DIR: a trial run must not replace the committed tables`,
      );
    }
    const seconds = await generate({
      trials,
      threads,
      out: values.out === undefined ? GENERATED_DIR : resolve(values.out),
      log: (line) => console.log(line),
    });
    console.log(`done in ${seconds.toFixed(1)} s`);
  } catch (error) {
    console.error(`gen-preflop: ${error instanceof Error ? error.message : String(error)}`);
    process.exitCode = 1;
  }
}
